// Pulls effect docs from the public Sanity dataset at build time, downloads each
// asset into public/online-fx and writes local paths into src/lib/sanityEffects.ts.
// Downloading at build time avoids the browser CORS block on cdn.sanity.io.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const project = "3mq2fyfh";
const dataset = "production";
const outDir = join("public", "online-fx");
const query =
  '*[_type=="effect" && defined(file.asset._ref)]{_id,title,"ref":file.asset._ref,"name":file.asset->originalFilename}|order(title asc)';
const endpoint = `https://${project}.api.sanity.io/v2025-01-01/data/query/${dataset}?query=${encodeURIComponent(query)}`;

try {
  const res = await fetch(endpoint);
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  const { result } = await res.json();

  mkdirSync(outDir, { recursive: true });
  const effects = [];
  for (const doc of result ?? []) {
    const parts = doc.ref?.split("-");
    if (parts?.[0] !== "file" || parts.length !== 3) continue;
    const ext = parts[2];
    const cdn = `https://cdn.sanity.io/files/${project}/${dataset}/${parts[1]}.${ext}`;
    const asset = await fetch(cdn);
    if (!asset.ok) throw new Error(`asset ${cdn}: ${asset.status}`);
    const local = `${doc._id}.${ext}`;
    writeFileSync(join(outDir, local), Buffer.from(await asset.arrayBuffer()));
    effects.push({
      id: doc._id,
      name: doc.title || doc.name || doc._id,
      url: `/online-fx/${local}`,
      file: doc.name || `effect.${ext}`,
    });
  }

  const body = `// Generated by scripts/sync-sanity-effects.mjs - do not edit.\nexport interface SanityEffect { id: string; name: string; url: string; file: string }\nexport const SANITY_EFFECTS: SanityEffect[] = ${JSON.stringify(effects, null, 2)};\n`;
  writeFileSync("src/lib/sanityEffects.ts", body);
  console.log(`sanity: ${effects.length} effect(s) synced`);
} catch (err) {
  // Keep the previous generated file and assets so a build still works offline.
  console.warn(`sanity: sync skipped (${err instanceof Error ? err.message : err}) - keeping previous effects`);
}
